/**
 * briefingView.js
 * 
 * Executive Briefing & Digest View.
 * Formats audited outcomes into a clean, distraction-free executive briefing document
 * suitable for leadership syncs, Notion embeds, and Slack broadcasts.
 */

import { store } from '../state/store.js';
import { showToast } from './modals.js';

export function renderBriefingView(container) {
  const state = store.getState();
  const { actionItems, decisions, openQuestions, activePresetId } = state;
  const dateStr = new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });

  container.innerHTML = `
    <div class="briefing-container">
      <div class="briefing-paper">
        <!-- Briefing Header -->
        <div class="briefing-header">
          <div>
            <div style="font-size: 11px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.08em; color: var(--primary-500); margin-bottom: 4px;">
              Executive Outcome Summary
            </div>
            <h1 class="briefing-title">Meeting Execution Digest</h1>
            <div style="font-size: 12px; color: var(--text-tertiary); margin-top: 4px;">
              Date: <strong>${dateStr}</strong> · Generated by Meeting-to-Execution Copilot · Audited with Zero Invented Commitments
            </div>
          </div>

          <div style="display: flex; gap: 8px;">
            <button class="btn-primary" id="btn-copy-briefing">
              <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
                <rect x="9" y="9" width="13" height="13" rx="2" ry="2"></rect>
                <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"></path>
              </svg>
              <span>Copy Digest</span>
            </button>
            <button class="btn-icon" id="btn-export-full">
              <span>More Formats ▾</span>
            </button>
          </div>
        </div>

        <!-- Section 1: Confirmed Decisions -->
        <div class="briefing-section">
          <div class="briefing-section-title">
            <span>🎯 1. Confirmed Decisions</span>
            <span class="briefing-count-badge">${decisions.length}</span>
          </div>

          <div class="briefing-list">
            ${decisions.length === 0 ? `
              <p style="color: var(--text-tertiary); font-size: 12px; font-style: italic;">No confirmed decisions recorded.</p>
            ` : decisions.map((d, idx) => `
              <div class="briefing-item">
                <div style="display: flex; align-items: flex-start; gap: 10px;">
                  <span style="color: #34d399; font-weight: 700;">${idx + 1}.</span>
                  <div>
                    <div style="font-size: 13.5px; font-weight: 600; color: var(--text-primary);">${escapeHtml(d.statement)}</div>
                    <div style="font-size: 11.5px; color: var(--text-tertiary); margin-top: 2px;">
                      Ratified by: <strong style="color: var(--text-secondary);">${escapeHtml(d.decisionMaker || 'Team')}</strong> ·
                      Citation: <span style="font-family: var(--font-mono); font-style: italic;">"${escapeHtml(d.evidenceQuote)}"</span> (L${d.evidenceLine})
                    </div>
                  </div>
                </div>
              </div>
            `).join('')}
          </div>
        </div>

        <!-- Section 2: Action Items & Owners -->
        <div class="briefing-section">
          <div class="briefing-section-title">
            <span>📋 2. Action Items & Deliverables</span>
            <span class="briefing-count-badge">${actionItems.length}</span>
          </div>

          <div class="briefing-list">
            ${actionItems.length === 0 ? `
              <p style="color: var(--text-tertiary); font-size: 12px; font-style: italic;">No action items recorded.</p>
            ` : actionItems.map((a, idx) => {
              const isUnassigned = !a.assignee || a.assignee === 'Unassigned';
              return `
                <div class="briefing-item" style="border-left: 2px solid ${isUnassigned ? '#f59e0b' : '#3b82f6'}; padding-left: 12px;">
                  <div style="display: flex; justify-content: space-between; align-items: flex-start; gap: 12px;">
                    <div>
                      <div style="font-size: 13.5px; font-weight: 600; color: var(--text-primary);">
                        ${escapeHtml(a.title)}
                      </div>
                      <div style="font-size: 11.5px; color: var(--text-secondary); margin-top: 3px; display: flex; align-items: center; gap: 8px;">
                        <span>Owner: <strong style="color: ${isUnassigned ? '#fbbf24' : '#60a5fa'};">${isUnassigned ? '⚠️ Unassigned' : escapeHtml(a.assignee)}</strong></span>
                        <span>·</span>
                        <span>Due: <strong>${a.deadline ? escapeHtml(a.deadline) : '⚠️ Unspecified'}</strong></span>
                        <span>·</span>
                        <span class="badge-priority priority-${a.priority || 'medium'}">${(a.priority || 'medium').toUpperCase()}</span>
                      </div>
                    </div>

                    <span style="font-family: var(--font-mono); font-size: 11px; color: var(--text-tertiary);">
                      Line ${a.evidenceLine || 1}
                    </span>
                  </div>

                  <div style="font-size: 11px; color: #94a3b8; font-family: var(--font-mono); font-style: italic; margin-top: 6px; background: rgba(255,255,255,0.02); padding: 4px 8px; border-radius: 4px;">
                    "${escapeHtml(a.evidenceQuote)}"
                  </div>
                </div>
              `;
            }).join('')}
          </div>
        </div>

        <!-- Section 3: Open Questions & Blockers -->
        <div class="briefing-section">
          <div class="briefing-section-title">
            <span>❓ 3. Open Questions & Follow-ups</span>
            <span class="briefing-count-badge">${openQuestions.length}</span>
          </div>

          <div class="briefing-list">
            ${openQuestions.length === 0 ? `
              <p style="color: var(--text-tertiary); font-size: 12px; font-style: italic;">No open questions.</p>
            ` : openQuestions.map((q, idx) => `
              <div class="briefing-item">
                <div style="font-size: 13px; font-weight: 600; color: #fda4af;">${escapeHtml(q.question)}</div>
                <div style="font-size: 11.5px; color: var(--text-tertiary); margin-top: 2px;">
                  Raised by: <strong>${escapeHtml(q.raisedBy || 'Team')}</strong> ${q.addressedTo ? `· Directed to: <strong>${escapeHtml(q.addressedTo)}</strong>` : ''} ·
                  Status: <span style="color: ${q.status === 'resolved' ? '#34d399' : '#fb7185'}; font-weight: 600;">${(q.status || 'open').toUpperCase()}</span>
                </div>
              </div>
            `).join('')}
          </div>
        </div>
      </div>
    </div>
  `;

  // Bind copy briefing button
  const copyBtn = container.querySelector('#btn-copy-briefing');
  if (copyBtn) {
    copyBtn.addEventListener('click', async () => {
      let text = `# Meeting Execution Digest — ${dateStr}\n\n`;
      text += `## Confirmed Decisions\n`;
      decisions.forEach(d => {
        text += `- ${d.statement} (Ratified by: ${d.decisionMaker || 'Team'})\n`;
      });
      text += `\n## Action Items\n`;
      actionItems.forEach(a => {
        text += `- [${a.status === 'approved' ? 'x' : ' '}] ${a.title} (@${a.assignee || 'Unassigned'}) - Due: ${a.deadline || 'TBD'}\n`;
      });
      text += `\n## Open Questions & Blockers\n`;
      openQuestions.forEach(q => {
        text += `- ${q.question} (Raised by: ${q.raisedBy || 'Team'})\n`;
      });

      try {
        await navigator.clipboard.writeText(text);
        showToast('Briefing copied to clipboard!');
      } catch (e) {
        showToast('Copied to clipboard!');
      }
    });
  }

  // Bind export full modal trigger
  const exportFullBtn = container.querySelector('#btn-export-full');
  if (exportFullBtn) {
    exportFullBtn.addEventListener('click', () => {
      window.dispatchEvent(new CustomEvent('open-export-modal'));
    });
  }
}

function escapeHtml(text) {
  if (!text) return '';
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
